def get_volume_of_cuboid(length, width, height):
    """
        Calcula el volumen de un cuboide rectangular.
        Arg:    
            length (float o int): Longitud del cuboide.
            width (float o int): Anchura del cuboide.
            height (float o int): Altura del cuboide.

        Return:
            float o int: Volumen del cuboide, calculado como length × width × height.
    """
    # Se multiplican las tres valores para obtener el volumen
    return length * width * height